        if (desirePath.LowActionScore < _smallestLowActionScore)
        {
            _smallestLowActionScore = desirePath.LowActionScore;
        }

        if (!DesirePathUtil.IsCompletionWorthwhile(desirePath))
        {
            IsPathWorthwhile = false;
        }

    }


        if (IsInked)
        {
            return;
        }

        _myTracks.Add(new Point(x, y));
        _allTracks.Add(new Point(x, y));
    }

    internal void AddOpponentTrack(int x, int y)
    {
        if (IsInked)
        {
            return;
        }

        _opponentTracks.Add(new Point(x, y));
